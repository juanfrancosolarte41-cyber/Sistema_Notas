    private void GuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_GuardarActionPerformed
        String nom = nombre.getText().trim();
        String cod = Codigo.getText().trim();

        if (nom.isEmpty() || cod.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Debe ingresar nombre y código.");
            return;
        }

        try {
            double n1 = Double.parseDouble(Nota_1.getText().trim().replace(",", "."));
            double n2 = Double.parseDouble(Nota_2.getText().trim().replace(",", "."));
            double n3 = Double.parseDouble(Nota_3.getText().trim().replace(",", "."));

            if (!tabla.notaValida(n1) || !tabla.notaValida(n2) || !tabla.notaValida(n3)) {
                javax.swing.JOptionPane.showMessageDialog(this, "Las notas deben estar entre 0.0 y 5.0");
                return;
            }

            tabla.agregarEstudiante(cod, nom, n1, n2, n3);
            limpiarCampos();

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Las notas deben ser números válidos (ej: 3.5)");
        }
    }//GEN-LAST:event_GuardarActionPerformed


